/**
 * Tests for the key pair and certificate generated by {@link KeyStoreGenerator} for new tenants.
 */
public class KeyStoreGeneratorTest {

    private static final int TENANT_ID = 1;
    private static final String TENANT_DOMAIN = "wso2.com";
    private static final String TENANT_EC_KEY_ALIAS = "wso2.com_ec";
    private static final String KEY_ALGORITHM_CONFIG = "Security.TenantKeyStore.KeyAlgorithm";
    private static final String KEY_SIZE_CONFIG = "Security.TenantKeyStore.KeySize";
    private static final String KEYSTORE_TYPE_CONFIG = "Security.TenantKeyStore.Type";
    private static final String SIGNING_ALG_CONFIG = "Tenant.SigningAlgorithm";
    private static final long CERT_NOT_BEFORE_OFFSET = TimeUnit.DAYS.toMillis(30);
    private static final long CERT_NOT_AFTER_OFFSET = TimeUnit.DAYS.toMillis(365 * 10);
    private static final long TIME_TOLERANCE = TimeUnit.MINUTES.toMillis(5);

    private MockedStatic<ServerConfiguration> serverConfigurationStatic;
    private MockedStatic<CarbonUtils> carbonUtils;
    private MockedStatic<CryptoUtil> cryptoUtil;
    private MockedConstruction<KeyStoreAdmin> keyStoreAdminConstruction;
    private ServerConfiguration serverConfiguration;
    private PersistedKeyStore persistedKeyStore;

    @BeforeMethod
    public void setUp() throws Exception {

        if (Security.getProvider(BouncyCastleProvider.PROVIDER_NAME) == null) {
            Security.addProvider(new BouncyCastleProvider());
        }

        serverConfiguration = mock(ServerConfiguration.class);
        when(serverConfiguration.getFirstProperty(KEYSTORE_TYPE_CONFIG)).thenReturn("PKCS12");
        serverConfigurationStatic = mockStatic(ServerConfiguration.class);
        serverConfigurationStatic.when(ServerConfiguration::getInstance).thenReturn(serverConfiguration);
        carbonUtils = mockStatic(CarbonUtils.class);
        carbonUtils.when(CarbonUtils::getServerConfiguration).thenReturn(serverConfiguration);
        cryptoUtil = mockStatic(CryptoUtil.class);

        TenantManager tenantManager = mock(TenantManager.class);
        when(tenantManager.getDomain(TENANT_ID)).thenReturn(TENANT_DOMAIN);
        RealmService realmService = mock(RealmService.class);
        when(realmService.getTenantManager()).thenReturn(tenantManager);
        RealmServiceHolder.setRealmService(realmService);

        // Capture the keystore that the generator persists, instead of writing it to the registry.
        persistedKeyStore = null;
        keyStoreAdminConstruction = mockConstruction(KeyStoreAdmin.class, (keyStoreAdmin, context) ->
                doAnswer(invocation -> {
                    persistedKeyStore = new PersistedKeyStore(invocation.getArgument(0),
                            invocation.getArgument(2), invocation.getArgument(4));
                    return null;
                }).when(keyStoreAdmin).addKeyStore(any(byte[].class), anyString(), anyString(), anyString(),
                        anyString(), anyString()));
    }

    @AfterMethod
    public void tearDown() throws Exception {

        keyStoreAdminConstruction.close();
        cryptoUtil.close();
        carbonUtils.close();
        serverConfigurationStatic.close();
        RealmServiceHolder.setRealmService(null);
    }

    @Test
    public void testDefaultKeyConfiguration() throws Exception {

        long now = System.currentTimeMillis();
        new KeyStoreGenerator(TENANT_ID).generateKeyStore();

        X509Certificate certificate = getPersistedCertificate();
        assertEquals(certificate.getPublicKey().getAlgorithm(), "RSA");
        assertEquals(((RSAPublicKey) certificate.getPublicKey()).getModulus().bitLength(), 2048);
        assertEquals(((RSAPrivateKey) getPersistedPrivateKey()).getModulus().bitLength(), 2048);
        assertSelfSignedCertificate(certificate, now);
    }

    @DataProvider(name = "validKeySizes")
    public Object[][] validKeySizes() {

        return new Object[][]{{"2048", 2048}, {"3072", 3072}, {"4096", 4096}};
    }

    @Test(dataProvider = "validKeySizes")
    public void testConfiguredKeySize(String configuredKeySize, int expectedKeySize) throws Exception {

        when(serverConfiguration.getFirstProperty(KEY_ALGORITHM_CONFIG)).thenReturn("RSA");
        when(serverConfiguration.getFirstProperty(KEY_SIZE_CONFIG)).thenReturn(configuredKeySize);
        long now = System.currentTimeMillis();
        new KeyStoreGenerator(TENANT_ID).generateKeyStore();

        X509Certificate certificate = getPersistedCertificate();
        RSAPublicKey publicKey = (RSAPublicKey) certificate.getPublicKey();
        RSAPrivateKey privateKey = (RSAPrivateKey) getPersistedPrivateKey();
        assertEquals(publicKey.getModulus().bitLength(), expectedKeySize);
        assertEquals(privateKey.getModulus(), publicKey.getModulus());
        assertSelfSignedCertificate(certificate, now);
    }

    @DataProvider(name = "invalidKeyConfigurations")
    public Object[][] invalidKeyConfigurations() {

        return new Object[][]{
                {KEY_SIZE_CONFIG, "1024", "Invalid key size '1024'"},
                {KEY_SIZE_CONFIG, "2047", "Invalid key size '2047'"},
                {KEY_SIZE_CONFIG, "3000", "Invalid key size '3000'"},
                {KEY_SIZE_CONFIG, "abc", "Invalid key size 'abc'"},
                {KEY_SIZE_CONFIG, "16384", "Invalid key size '16384'"},
                {KEY_ALGORITHM_CONFIG, "EC", "Unsupported key algorithm 'EC'"},
                {KEY_ALGORITHM_CONFIG, "DSA", "Unsupported key algorithm 'DSA'"}
        };
    }

    @Test(dataProvider = "invalidKeyConfigurations")
    public void testInvalidKeyConfiguration(String configKey, String configValue, String expectedMessage)
            throws Exception {

        when(serverConfiguration.getFirstProperty(configKey)).thenReturn(configValue);
        KeyStoreGenerator keyStoreGenerator = new KeyStoreGenerator(TENANT_ID);

        KeyStoreMgtException e = expectThrows(KeyStoreMgtException.class, keyStoreGenerator::generateKeyStore);
        assertTrue(e.getMessage().contains(expectedMessage), e.getMessage());
        assertKeyStoreNotPersisted();
    }

    @Test
    public void testTenantCreationFailsOnInvalidKeySize() throws Exception {

        when(serverConfiguration.getFirstProperty(KEY_SIZE_CONFIG)).thenReturn("1024");
        TenantInfoBean tenantInfo = new TenantInfoBean();
        tenantInfo.setTenantId(TENANT_ID);

        StratosException e = expectThrows(StratosException.class,
                () -> new KeystoreTenantMgtListener().onTenantCreate(tenantInfo));
        assertTrue(e.getMessage().contains("Invalid key size '1024'"), e.getMessage());
        assertKeyStoreNotPersisted();
    }

    @Test
    public void testTenantCreationWithConfiguredKeySize() throws Exception {

        when(serverConfiguration.getFirstProperty(KEY_SIZE_CONFIG)).thenReturn("3072");
        TenantInfoBean tenantInfo = new TenantInfoBean();
        tenantInfo.setTenantId(TENANT_ID);

        new KeystoreTenantMgtListener().onTenantCreate(tenantInfo);
        assertEquals(((RSAPublicKey) getPersistedCertificate().getPublicKey()).getModulus().bitLength(), 3072);
    }

    @DataProvider(name = "signatureAlgorithms")
    public Object[][] signatureAlgorithms() {

        return new Object[][]{
                {null, "MD5withRSA"},
                {"", "MD5withRSA"},
                {"unknown", "MD5withRSA"},
                {"SHA256withRSA", "SHA256withRSA"},
                {"SHA384withRSA", "SHA384withRSA"},
                {"sha512withrsa", "SHA512withRSA"},
                {"MD5withRSA", "MD5withRSA"},
                {"SHA1withRSA", "SHA1withRSA"}
        };
    }

    @Test(dataProvider = "signatureAlgorithms")
    public void testCertificateSignatureAlgorithm(String configuredAlgorithm, String expectedAlgorithm)
            throws Exception {

        when(serverConfiguration.getFirstProperty(SIGNING_ALG_CONFIG)).thenReturn(configuredAlgorithm);
        new KeyStoreGenerator(TENANT_ID).generateKeyStore();

        X509Certificate certificate = getPersistedCertificate();
        assertTrue(expectedAlgorithm.equalsIgnoreCase(certificate.getSigAlgName()),
                "Expected " + expectedAlgorithm + " but was " + certificate.getSigAlgName());
        certificate.verify(certificate.getPublicKey());
    }

    @Test
    public void testECKeyEntryGenerated() throws Exception {

        long now = System.currentTimeMillis();
        new KeyStoreGenerator(TENANT_ID).generateKeyStore();

        KeyStore keyStore = loadPersistedKeyStore();
        assertTrue(keyStore.isKeyEntry(TENANT_DOMAIN), "RSA key entry should be generated.");
        assertEquals(keyStore.getCertificate(TENANT_DOMAIN).getPublicKey().getAlgorithm(), "RSA");
        assertTrue(keyStore.isKeyEntry(TENANT_EC_KEY_ALIAS), "EC key entry should be generated.");
        assertECKeyEntry(keyStore, persistedKeyStore.password, now);
    }

    @Test
    public void testAddECKeyEntryToExistingKeyStore() throws Exception {

        String password = "password";
        KeyStore keyStore = KeystoreUtils.getKeystoreInstance("PKCS12");
        keyStore.load(null, password.toCharArray());
        long now = System.currentTimeMillis();

        X509Certificate certificate = TenantKeyPairUtil.addECKeyEntry(keyStore, TENANT_DOMAIN, password);

        assertEquals(keyStore.getCertificate(TENANT_EC_KEY_ALIAS), certificate);
        assertECKeyEntry(keyStore, password, now);
    }

    private void assertECKeyEntry(KeyStore keyStore, String password, long generatedAt) throws Exception {

        X509Certificate certificate = (X509Certificate) keyStore.getCertificate(TENANT_EC_KEY_ALIAS);
        ECPublicKey publicKey = (ECPublicKey) certificate.getPublicKey();
        ECPrivateKey privateKey = (ECPrivateKey) keyStore.getKey(TENANT_EC_KEY_ALIAS, password.toCharArray());
        assertEquals(publicKey.getParams().getCurve().getField().getFieldSize(), 256);
        assertEquals(privateKey.getParams().getCurve(), publicKey.getParams().getCurve());
        assertTrue("SHA256withECDSA".equalsIgnoreCase(certificate.getSigAlgName()),
                "Expected SHA256withECDSA but was " + certificate.getSigAlgName());
        assertSelfSignedCertificate(certificate, generatedAt);
    }

    private void assertSelfSignedCertificate(X509Certificate certificate, long generatedAt) throws Exception {

        assertEquals(certificate.getSubjectX500Principal(), certificate.getIssuerX500Principal());
        assertTrue(certificate.getSubjectX500Principal().getName().contains("CN=" + TENANT_DOMAIN));
        certificate.verify(certificate.getPublicKey());
        assertWithinTolerance(certificate.getNotBefore().getTime(), generatedAt - CERT_NOT_BEFORE_OFFSET);
        assertWithinTolerance(certificate.getNotAfter().getTime(), generatedAt + CERT_NOT_AFTER_OFFSET);
    }

    private void assertWithinTolerance(long actual, long expected) {

        assertTrue(Math.abs(actual - expected) < TIME_TOLERANCE,
                "Expected a time close to " + expected + " but was " + actual);
    }

    private void assertKeyStoreNotPersisted() throws Exception {

        assertEquals(persistedKeyStore, null);
        List<KeyStoreAdmin> keyStoreAdmins = keyStoreAdminConstruction.constructed();
        for (KeyStoreAdmin keyStoreAdmin : keyStoreAdmins) {
            verify(keyStoreAdmin, never()).addKeyStore(any(byte[].class), anyString(), anyString(), anyString(),
                    anyString(), anyString());
        }
    }

    private KeyStore loadPersistedKeyStore() throws Exception {

        assertNotNull(persistedKeyStore, "The tenant keystore was not persisted.");
        KeyStore keyStore = KeystoreUtils.getKeystoreInstance(persistedKeyStore.type);
        keyStore.load(new ByteArrayInputStream(persistedKeyStore.content), persistedKeyStore.password.toCharArray());
        return keyStore;
    }

    private X509Certificate getPersistedCertificate() throws Exception {

        return (X509Certificate) loadPersistedKeyStore().getCertificate(TENANT_DOMAIN);
    }

    private java.security.Key getPersistedPrivateKey() throws Exception {

        return loadPersistedKeyStore().getKey(TENANT_DOMAIN, persistedKeyStore.password.toCharArray());
    }

    /**
     * Keystore content and password passed to {@link KeyStoreAdmin} for persistence.
     */
    private static class PersistedKeyStore {

        private final byte[] content;
        private final String password;
        private final String type;

        PersistedKeyStore(byte[] content, String password, String type) {

            this.content = content;
            this.password = password;
            this.type = type;
        }
    }
}
